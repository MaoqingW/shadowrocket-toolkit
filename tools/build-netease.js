import { build } from 'esbuild'
import { readFileSync } from 'node:fs'
import { fileURLToPath, URL } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
await build({
  absWorkingDir: root,
  entryPoints: ['src/netease/home.js'],
  outfile: 'scripts/netease/home.js',
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2018',
  minify: true,
  legalComments: 'eof',
  banner: {
    js: '// Generated by npm run build:netease; edit src/netease/home.js.',
  },
  footer: {
    js:
      '/* Bundled dependency licenses:\n' +
      ['crypto-js', 'pako']
        .map((name) =>
          readFileSync(`${root}/node_modules/${name}/LICENSE`, 'utf8').replace(
            /[\t ]+$/gm,
            '',
          ),
        )
        .join('\n\n') +
      '\n*/',
  },
})
